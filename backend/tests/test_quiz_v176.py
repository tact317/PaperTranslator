def test_coordinated_main_predicate_is_core() -> None:
    assert m._normalize_quiz_unit_importance(
        "and allow experiments to be carried out", "support", 4, 6
    ) == "core"
    assert m._normalize_quiz_unit_importance(
        "but reduces the phase error", "support", 3, 5
    ) == "core"


def test_pure_modifiers_are_not_promoted_to_core() -> None:
    assert m._normalize_quiz_unit_importance(
        "by over one order of magnitude", "core", 2, 6
    ) == "support"
    assert m._normalize_quiz_unit_importance(
        "with photon energies in excess of 60 keV", "detail", 5, 6
    ) == "detail"


def _field_units() -> list[m.SemanticUnit]:
    rows = [
        ("The very hard x-ray source generated by the BHTSU", "core", "partial"),
        ("will increase the brilliance at the beamline", "core", "partial"),
        ("by over one order of magnitude", "support", "correct"),
        ("in comparison to other state-of-the-art undulator technologies", "support", "correct"),
        ("and allow experiments to be carried out", "support", "missing"),
        ("with photon energies in excess of 60 keV", "support", "correct"),
    ]
    units: list[m.SemanticUnit] = []
    for index, (source, requested, status) in enumerate(rows):
        importance = m._normalize_quiz_unit_importance(source, requested, index, len(rows))
        units.append(m.SemanticUnit(
            id=f"u{index + 1}", source=source, translation=f"訳{index + 1}",
            importance=importance, status=status, note="",
        ))
    return units


def test_field_case_major_predicate_and_awkward_japanese_scores_mid_70s() -> None:
    evaluation = m.TranslationEvaluation(
        verdict="partial", score=0, feedback="", reference_translation="基準訳",
        semantic_units=_field_units(),
        japanese_quality=m.JapaneseQuality(
            level="awkward",
            note="主述関係と助詞がぎこちなく、直訳調です。",
        ),
    )
    out = m._apply_semantic_scoring(evaluation)
    allow_unit = next(u for u in out.semantic_units if u.source.startswith("and allow"))
    assert allow_unit.importance == "core"
    assert allow_unit.max_points == 14
    assert allow_unit.earned_points == 0
    assert out.score_breakdown.meaning == 50
    assert out.score_breakdown.japanese == 10
    assert out.score == 75
    assert out.verdict == "partial"


def test_japanese_quality_axis_is_independent_and_deterministic() -> None:
    unit = m.SemanticUnit(
        id="u1", source="The result is stable", translation="結果は安定している",
        importance="core", status="correct",
    )
    expected = {"natural": 100, "minor": 98, "awkward": 95, "broken": 91}
    for level, total in expected.items():
        evaluation = m.TranslationEvaluation(
            verdict="correct", score=100, feedback="", reference_translation="基準訳",
            semantic_units=[unit],
            japanese_quality=m.JapaneseQuality(level=level, note="test"),
        )
        out = m._apply_semantic_scoring(evaluation)
        assert out.score == total
        assert out.score_breakdown.meaning == 70
        assert out.score_breakdown.terminology == 15


def test_normalize_evaluation_reads_japanese_quality() -> None:
    raw = {
        "score": 100,
        "verdict": "correct",
        "feedback": "ok",
        "reference_translation": "基準訳",
        "semantic_units": [{
            "id": "u1", "source": "source", "translation": "訳",
            "importance": "core", "status": "correct", "note": "",
        }],
        "japanese_quality": {"level": "awkward", "note": "直訳調です。"},
        "key_points": [],
        "issues": [],
        "syntax_focus": {"needed": False, "relations": []},
    }
    out = m._normalize_evaluation(raw)
    assert out.japanese_quality.level == "awkward"
    assert out.japanese_quality.note == "直訳調です。"


